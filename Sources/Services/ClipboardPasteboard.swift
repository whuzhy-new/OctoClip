import AppKit

enum ClipboardPasteboard {
    private static let imageFormats: [ImageFormat] = [.gif, .heic, .webp, .png, .jpeg, .tiff]
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")

    static func excludedApps(in defaults: UserDefaults) -> [ClipSource] {
        guard let data = defaults.data(forKey: SettingsKey.excludedApps) else { return [] }
        return (try? JSONDecoder().decode([ClipSource].self, from: data)) ?? []
    }

    static func readItem(from pb: NSPasteboard, excludedApps: [ClipSource], ownBundleID: String?,
                         activeApp app: NSRunningApplication? = nil,
                         candidateAppIDs: Set<String> = []) -> ClipboardItem? {
        guard let types = pb.types, Self.skippedTypes.isDisjoint(with: types) else { return nil }
        let explicitID = pb.string(forType: Self.sourceType)?.trimmingCharacters(in: .whitespacesAndNewlines)
        let sourceID = explicitID.flatMap { $0.isEmpty ? nil : $0 } ?? app?.bundleIdentifier
        if excludedApps.contains(where: { $0.bundleID == sourceID }) { return nil }
        if explicitID?.isEmpty != false,
           excludedApps.contains(where: { candidateAppIDs.contains($0.bundleID) }) { return nil }

        let source = sourceID.flatMap { id -> ClipSource? in
            guard id != ownBundleID else { return nil }
            let name = id == app?.bundleIdentifier ? app?.localizedName :
                NSWorkspace.shared.urlForApplication(withBundleIdentifier: id).map {
                    FileManager.default.displayName(atPath: $0.path)
                }
            return ClipSource(bundleID: id, name: name ?? id)
        }
        let sourceURL = pb.string(forType: .URL).flatMap(ClipDocument.webURL)
        var item: ClipboardItem?

        if types.contains(.fileURL) {
            item = readFiles(pb)
        } else if let format = Self.imageFormats.first(where: { types.contains($0.pasteboardType) }) {
            item = readImage(pb, format: format)
        } else if types.contains(.string) || types.contains(.rtf) || types.contains(.html) || sourceURL != nil {
            item = readText(pb, url: sourceURL)
        }
        guard var item else { return nil }
        item.source = source
        item.sourceURL = sourceURL
        return item
    }

    private static func readText(_ pb: NSPasteboard, url: URL?) -> ClipboardItem? {
        let plainText = pb.string(forType: .string) ?? url?.absoluteString
        let rtfData = pb.data(forType: .rtf)
        let htmlData = pb.data(forType: .html)

        guard plainText != nil || rtfData != nil || htmlData != nil else { return nil }

        return ClipboardItem(
            id: UUID(),
            type: .text,
            timestamp: Date(),
            plainText: plainText,
            rtfData: rtfData,
            htmlData: htmlData,
            imageData: nil,
            imageFormat: nil,
            fileURLs: nil
        )
    }

    private static func readImage(_ pb: NSPasteboard, format: ImageFormat) -> ClipboardItem? {
        let extracted: (data: Data, format: ImageFormat)? = {
            if let data = pb.data(forType: format.pasteboardType) {
                return (data, format)
            }
            // fallback: 通过 NSImage 转 PNG
            guard let image = NSImage(pasteboard: pb),
                  let tiffData = image.tiffRepresentation,
                  let bitmap = NSBitmapImageRep(data: tiffData),
                  let pngData = bitmap.representation(using: .png, properties: [:]) else { return nil }
            return (pngData, .png)
        }()

        guard let (data, format) = extracted else { return nil }

        return ClipboardItem(
            id: UUID(),
            type: .image,
            timestamp: Date(),
            plainText: nil,
            rtfData: nil,
            htmlData: nil,
            imageData: data,
            imageFormat: format,
            fileURLs: nil
        )
    }

    private static func readFiles(_ pb: NSPasteboard) -> ClipboardItem? {
        let options: [NSPasteboard.ReadingOptionKey: Any] = [.urlReadingFileURLsOnly: true]
        guard let urls = pb.readObjects(forClasses: [NSURL.self], options: options) as? [URL],
              !urls.isEmpty else { return nil }

        return ClipboardItem(
            id: UUID(),
            type: .file,
            timestamp: Date(),
            plainText: nil,
            rtfData: nil,
            htmlData: nil,
            imageData: nil,
            imageFormat: nil,
            fileURLs: urls
        )
    }
}
